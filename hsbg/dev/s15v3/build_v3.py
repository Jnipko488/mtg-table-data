"""Build Season 15 v3 from slot 227: python3 build_v3.py <out.json> "<SaveName>"
Inserts v3data.lua (generated by gen_data.py from Blizzard's card library) and lua/v3fix.lua, plus small anchored edits."""
import json, sys, os
SRC = '/tmp/unf/HSBG_Season15_Unfinished/saves/TS_Save_227.json'
HERE = os.path.dirname(os.path.abspath(__file__))
out, name = sys.argv[1], sys.argv[2]
save = json.load(open(SRC))
obj = [o for o in save['ObjectStates'] if o.get('GUID') == 'b9a001'][0]
s = obj['LuaScript']

def replace(s, old, new, count=1):
    n = s.count(old)
    if n != count:
        raise SystemExit('anchor matched %d times (want %d): %r' % (n, count, old[:80]))
    return s.replace(old, new)

data = open(os.path.join(HERE, 'v3data.lua')).read()
fix = open(os.path.join(HERE, 'lua', 'v3fix.lua')).read()
for extra in sorted(os.listdir(os.path.join(HERE, 'lua'))):
    if extra.startswith('v3_') and extra.endswith('.lua'):
        fix += '\n' + open(os.path.join(HERE, 'lua', extra)).read()
block = '\n'.join('    ' + l if l.strip() else l for l in data.splitlines()) + '\n' + fix + '\n'
s = replace(s, '    register("S15_great_wolf_cub", {bc = function(g, p, _, k) spells(g, p, GB, k) end})',
            block + '    register("S15_great_wolf_cub", {bc = function(g, p, _, k) spells(g, p, GB, k) end})')
# Timewarped Voidpriest: golden copies up to 6 cards per turn.
s = replace(s, '                if m.voidCount < 3 then', '                if m.voidCount < 3 * k then')
art = os.path.join(HERE, 'art_patch.py')
if os.path.exists(art):
    ns = {}
    exec(open(art).read(), ns)
    s = ns['patch'](s, replace)
obj['LuaScript'] = s
save['SaveName'] = name
open(os.path.join(HERE, 'b9a001_v3.lua'), 'w').write(s)
json.dump(save, open(out, 'w'), indent=2)
print('ok', len(s))
